function mk(actionsPerStep: Array<{ tool?: string; repro?: unknown }>, extra: Partial<BrowseTrace> = {}): BrowseTrace {
  return {
    format: "sideform.browse-trace",
    version: 1,
    id: "t1",
    goal: "Add an item to the cart",
    startedAt: 0,
    endedAt: 1,
    status: "done",
    steps: actionsPerStep.map((s, i) => ({ index: i, tool: s.tool ?? "browse_act", args: {}, startedAt: 0, endedAt: 1, ok: true, ...(s.repro !== undefined ? { repro: s.repro as BrowseTraceReproAction[] } : {}) })),
    frames: [],
    console: [],
    network: [],
    repro: {},
    ...extra,
  } as BrowseTrace;
}

function render(trace: BrowseTrace, opts?: { title?: string }) {
  const r = browseTraceToPlaywrightSpec(trace, opts);
  if (!r.ok) throw new Error(r.error);
  return r;
}

function syntaxErrors(code: string): string[] {
  const out = ts.transpileModule(code, { reportDiagnostics: true, compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext }, fileName: "x.spec.ts" });
  return (out.diagnostics ?? []).map((d) => ts.flattenDiagnosticMessageText(d.messageText, "\n"));
}

