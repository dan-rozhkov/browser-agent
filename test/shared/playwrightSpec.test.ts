const routeRegex = (code: string, nth = 0): RegExp => {
  const found = [...code.matchAll(/page\.route\(new RegExp\(("(?:[^"\\]|\\.)*")\)/g)];
  return new RegExp(JSON.parse(found[nth]![1]!) as string);
};

